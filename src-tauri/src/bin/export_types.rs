use std::{fs, path::PathBuf};
use ts_rs::{Config, TS};
use vsedi_lib::{
    errors::{AppError, ErrorCode},
    models::{
        AppSettings, ApplyIgnoreRulesRequest, ChangeKind, ChangedFile, CommitDetail,
        ConfigFileDiagnostic, DiagnosticSeverity, DiagnosticStatus, EnvironmentDiagnostic,
        FileDiagnosticStatus, FileDiff, FileDiffKind, GitCommandEvent, GitCommandPhase,
        GitDiagnostic, GitOutputStream, HistoryEntry, HistoryPage, IgnoreFilePreview,
        IgnoreTemplateSettings, InitializeRepositoryRequest, LogSnapshot, PlatformDiagnostic,
        ProjectDiagnostic, ProjectIssue, ProjectKind, ProjectStatus, RecentProject,
        RecentProjectStatus, RepositoryBlockingReason, RepositoryDiagnostic,
        RepositoryIgnorePreview, RepositoryInitializationPreview, RepositorySettings,
        RepositoryState, RepositoryTreeFile, RepositoryTreeSnapshot, SaveRequest, SaveResult,
        SettingsLoadResult, SourceControlDiagnostic, VpmDiagnostic, VpmPackage, VpmTrackingPolicy,
        WorktreeSnapshot,
    },
};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let config = Config::default();
    let generated = [
        ErrorCode::export_to_string(&config)?,
        AppError::export_to_string(&config)?,
        DiagnosticStatus::export_to_string(&config)?,
        GitDiagnostic::export_to_string(&config)?,
        PlatformDiagnostic::export_to_string(&config)?,
        EnvironmentDiagnostic::export_to_string(&config)?,
        ProjectStatus::export_to_string(&config)?,
        ProjectKind::export_to_string(&config)?,
        DiagnosticSeverity::export_to_string(&config)?,
        FileDiagnosticStatus::export_to_string(&config)?,
        ProjectIssue::export_to_string(&config)?,
        ConfigFileDiagnostic::export_to_string(&config)?,
        VpmPackage::export_to_string(&config)?,
        VpmDiagnostic::export_to_string(&config)?,
        RepositoryDiagnostic::export_to_string(&config)?,
        SourceControlDiagnostic::export_to_string(&config)?,
        ProjectDiagnostic::export_to_string(&config)?,
        RepositoryBlockingReason::export_to_string(&config)?,
        RepositoryState::export_to_string(&config)?,
        ChangeKind::export_to_string(&config)?,
        ChangedFile::export_to_string(&config)?,
        WorktreeSnapshot::export_to_string(&config)?,
        RepositoryTreeFile::export_to_string(&config)?,
        RepositoryTreeSnapshot::export_to_string(&config)?,
        IgnoreFilePreview::export_to_string(&config)?,
        RepositoryInitializationPreview::export_to_string(&config)?,
        RepositoryIgnorePreview::export_to_string(&config)?,
        ApplyIgnoreRulesRequest::export_to_string(&config)?,
        InitializeRepositoryRequest::export_to_string(&config)?,
        SaveRequest::export_to_string(&config)?,
        GitCommandPhase::export_to_string(&config)?,
        GitOutputStream::export_to_string(&config)?,
        GitCommandEvent::export_to_string(&config)?,
        SaveResult::export_to_string(&config)?,
        HistoryEntry::export_to_string(&config)?,
        HistoryPage::export_to_string(&config)?,
        CommitDetail::export_to_string(&config)?,
        FileDiffKind::export_to_string(&config)?,
        FileDiff::export_to_string(&config)?,
        RecentProject::export_to_string(&config)?,
        RecentProjectStatus::export_to_string(&config)?,
        RepositorySettings::export_to_string(&config)?,
        VpmTrackingPolicy::export_to_string(&config)?,
        IgnoreTemplateSettings::export_to_string(&config)?,
        AppSettings::export_to_string(&config)?,
        SettingsLoadResult::export_to_string(&config)?,
        LogSnapshot::export_to_string(&config)?,
    ]
    .into_iter()
    .map(strip_imports)
    .collect::<Vec<_>>()
    .join("\n\n");
    let destination =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/generated/bindings.ts");
    fs::create_dir_all(destination.parent().expect("generated type parent"))?;
    fs::write(
        destination,
        format!("// Generated by `pnpm generate-types`; do not edit.\n\n{generated}\n"),
    )?;
    Ok(())
}

fn strip_imports(binding: String) -> String {
    binding
        .lines()
        .filter(|line| {
            !line.starts_with("import type ")
                && !line.starts_with("// This file was generated by [ts-rs]")
        })
        .collect::<Vec<_>>()
        .join("\n")
        .trim()
        .to_owned()
}
